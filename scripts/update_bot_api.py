#!/usr/bin/env python3
"""Generate generic Lua wrappers for Telegram Bot API methods missing in titogramlua."""

from __future__ import annotations

import html.parser
import pathlib
import re
import urllib.request

API_URL = "https://core.telegram.org/bots/api"
METHODS_OUTPUT = pathlib.Path("src/methods/generated.lua")


class MethodsParser(html.parser.HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.heading_depth = 0
        self.heading_text: list[str] = []
        self.in_methods = False
        self.in_method_heading = False
        self.method_text: list[str] = []
        self.methods: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in ("h2", "h3"):
            self.heading_depth = 1
            self.heading_text = []
        elif self.heading_depth and tag in ("h2", "h3"):
            self.heading_depth += 1
        elif tag == "h4" and self.in_methods:
            self.in_method_heading = True
            self.method_text = []

    def handle_endtag(self, tag: str) -> None:
        if tag == "h4" and self.in_method_heading:
            name = "".join(self.method_text).strip()
            if re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name):
                self.methods.add(name)
            self.in_method_heading = False
        if tag in ("h2", "h3") and self.heading_depth:
            self.heading_depth -= 1
            if not self.heading_depth:
                heading = " ".join("".join(self.heading_text).lower().split())
                if "available methods" in heading:
                    self.in_methods = True
                elif "available types" in heading:
                    self.in_methods = False

    def handle_data(self, data: str) -> None:
        if self.heading_depth:
            self.heading_text.append(data)
        if self.in_method_heading:
            self.method_text.append(data)


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def main() -> None:
    request = urllib.request.Request(API_URL, headers={"User-Agent": "titogramlua-bot-api-updater"})
    with urllib.request.urlopen(request, timeout=30) as response:
        document = response.read().decode("utf-8")

    parser = MethodsParser()
    parser.feed(document)
    if not parser.methods:
        raise RuntimeError("No Bot API methods found; refusing to replace generated wrappers.")

    implemented: set[str] = set()
    for path in pathlib.Path("src/methods").glob("*.lua"):
        if path == METHODS_OUTPUT:
            continue
        source = path.read_text(encoding="utf-8")
        implemented.update(re.findall(r"function\\s+api\\.([a-z][a-z0-9_]*)\\s*\\(", source))

    wrappers = []
    for method in sorted(parser.methods, key=str.casefold):
        lua_name = snake_case(method)
        if lua_name in implemented:
            continue
        wrappers.extend([
            f"    --- Generated from the official Bot API method {method}.",
            f"    -- Pass its parameters as an options table; see https://core.telegram.org/bots/api#{method.lower()}.",
            f"    function api.{lua_name}(opts, files)",
            f"        return api.call_method('{method}', opts, files)",
            "    end",
            "",
        ])

    output = (
        "--- Generated by scripts/update_bot_api.py; do not edit by hand.\\n"
        "--- New methods accept (opts, files); nested parameter tables are JSON-encoded.\\n"
        "return function(api)\\n"
        + "\\n".join(wrappers)
        + "end\\n"
    )
    METHODS_OUTPUT.write_text(output, encoding="utf-8")
    print(f"Found {len(parser.methods)} official methods; generated {len(wrappers) // 6} wrappers.")


if __name__ == "__main__":
    main()
